import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import solc from "solc";
import { toFunctionSelector, keccak256 } from "viem";
import { buildCollection } from "./collection.mjs";

const projectRoot = fileURLToPath(new URL("../", import.meta.url));

export function compileContracts(extraSources = {}) {
  const dependencies = {};
  const input = {
    language: "Solidity",
    sources: {
      "CupscriptionsMarket.sol": {
        content: fs.readFileSync(path.join(projectRoot, "src/CupscriptionsMarket.sol"), "utf8"),
      },
      ...extraSources,
    },
    settings: {
      optimizer: { enabled: true, runs: 200 },
      evmVersion: "shanghai",
      outputSelection: { "*": { "*": ["abi", "evm.bytecode.object", "evm.deployedBytecode.object", "evm.deployedBytecode.immutableReferences", "metadata"] } },
    },
  };
  const output = JSON.parse(solc.compile(JSON.stringify(input), {
    import(name) {
      if (!name.startsWith("@openzeppelin/contracts/") || name.includes("..")) {
        return { error: "Unsupported contract import" };
      }
      const contents = fs.readFileSync(path.join(projectRoot, "node_modules", name), "utf8");
      dependencies[name] = { content: contents };
      return { contents };
    },
  }));
  const errors = (output.errors ?? []).filter((entry) => entry.severity === "error");
  if (errors.length) throw new Error(errors.map((entry) => entry.formattedMessage).join("\n"));
  for (const warning of output.errors ?? []) console.warn(warning.formattedMessage);
  // Include dependency contents so the standard JSON input is self-contained
  // for bytecode reproduction and explorer verification.
  Object.assign(input.sources, dependencies);
  return { input, output };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { input, output } = compileContracts();
  const market = output.contracts["CupscriptionsMarket.sol"].CupscriptionsMarket;
  const collection = buildCollection();
  const selectors = new Set(market.abi.filter((entry) => entry.type === "function").map(toFunctionSelector));
  for (const { id } of collection.entries) {
    if (selectors.has(id.slice(0, 10))) throw new Error(`Raw deposit selector collision for ${id}`);
  }
  const artifactDir = path.join(projectRoot, "artifacts");
  fs.mkdirSync(artifactDir, { recursive: true });
  fs.writeFileSync(path.join(artifactDir, "CupscriptionsMarket.json"), JSON.stringify({
    contractName: "CupscriptionsMarket",
    compiler: solc.version(),
    abi: market.abi,
    bytecode: `0x${market.evm.bytecode.object}`,
    deployedBytecode: `0x${market.evm.deployedBytecode.object}`,
  }, null, 2));
  fs.writeFileSync(path.join(artifactDir, "compiler-input.json"), JSON.stringify(input, null, 2));
  fs.writeFileSync(path.join(artifactDir, "collection.json"), JSON.stringify({
    root: collection.root, count: collection.count, sourceSha256: collection.sourceSha256,
  }, null, 2));
  const appDir = path.join(projectRoot, "../src/lib/market");
  fs.mkdirSync(appDir, { recursive: true });
  fs.writeFileSync(path.join(appDir, "abi.generated.ts"),
    `// Generated by npm run contracts:build. Do not edit manually.\nexport const marketAbi = ${JSON.stringify(market.abi, null, 2)} as const;\n`);
  fs.writeFileSync(path.join(appDir, "runtime.generated.json"), JSON.stringify({
    runtimeHash: keccak256(`0x${market.evm.deployedBytecode.object}`),
    immutableReferences: Object.values(market.evm.deployedBytecode.immutableReferences).flat(),
    collectionRoot: collection.root,
    collectionSourceSha256: collection.sourceSha256,
  }, null, 2));
  console.log(`Compiled CupscriptionsMarket (${market.evm.deployedBytecode.object.length / 2} deployed bytes).`);
  console.log(`Collection: ${collection.count} cups; root ${collection.root}`);
}
